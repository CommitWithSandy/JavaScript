// 4. Truthy vs. Falsy Values
// JavaScript allows non-boolean values to be evaluated inside logical conditions, 
// classifying them as either truthy (assumed true) or falsy (assumed false)
// .
// Falsy Values (always evaluate to false)
// :
// false
// 0 and -0
// 0n (BigInt zero)
// "" (empty string)
// null
// undefined
// NaN (Not a Number)

// Truthy Values (all values that are not falsy, including some surprising examples)
// :
// "0" (zero inside a string)
// 'false' (the string "false")
// " " (a string containing a space)
// [] (empty array)
// {} (empty object)
// function(){} (an empty function)
